'use client';

import Link from 'next/link';
import { CheckCircle2 } from 'lucide-react';

import { AppointmentCard } from './appointment-card';
import { buttonVariants } from '@/components/ui/button';
import { Card, CardContent, CardHeader } from '@/components/ui/card';
import { daysUntil, formatDateTime } from '@/lib/dates';
import type { Appointment } from '@/types/appointment';

/** Final step: the mock record that was just written, plus honest next actions. */
export function ConfirmationStep({ appointment, onBookAnother }: { appointment: Appointment; onBookAnother: () => void }) {
  const start = new Date(appointment.startAt);
  const days = daysUntil(start);

  return (
    <div className="space-y-5">
      <Card>
        <CardContent className="flex items-start gap-4">
          <CheckCircle2 aria-hidden className="mt-0.5 h-8 w-8 shrink-0 text-emerald-600" />
          <div className="space-y-1">
            <h2 className="text-lg font-semibold text-ink-900">Slot held in the demo store</h2>
            <p className="text-sm text-ink-600">
              Reference <span className="font-medium text-ink-900">{appointment.reference}</span> ·{' '}
              {formatDateTime(start)}
              {days === 0 ? ' (today)' : days === 1 ? ' (tomorrow)' : ` (in ${days} days)`}
            </p>
            <p className="text-sm text-ink-500">
              The status is <span className="font-medium">pending</span> — in a real system the clinic would confirm it.
              Nothing has been sent to the clinic, no payment has been taken, and no email or SMS was generated by this
              build.
            </p>
          </div>
        </CardContent>
      </Card>

      <AppointmentCard
        appointment={appointment}
        detailHref={`/patient/appointments/${appointment.id}`}
      />

      <Card>
        <CardHeader title="What happens next" description="Everything below is local demo behaviour." />
        <CardContent className="space-y-3">
          <ul className="list-disc space-y-1.5 pl-5 text-sm text-ink-600">
            <li>Reach the appointment detail page to review or cancel it.</li>
            <li>Cancelling releases the slot back into this browser&apos;s mock availability.</li>
            <li>Refreshing the page keeps the booking, because the mock store persists to localStorage.</li>
          </ul>
          <div className="flex flex-wrap gap-3 pt-1">
            <Link
              href="/patient/appointments"
              className={buttonVariants({ variant: 'primary', size: 'sm' })}
            >
              My appointments
            </Link>
            <button type="button" onClick={onBookAnother} className={buttonVariants({ variant: 'outline', size: 'sm' })}>
              Book another appointment
            </button>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
